const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");

const projectRoot = path.resolve(__dirname, "..");
const postsDirectory = path.join(projectRoot, "src", "blog", "posts");
const outputDirectory = path.join(projectRoot, "src", "blog", "generated");
const outputFile = path.join(outputDirectory, "posts.js");
const requiredTextFields = ["title", "summary", "publishedAt"];

function fail(message) {
  throw new Error(`[blog:build] ${message}`);
}

function validatePost(slug, data, sourcePath) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
    fail(`${sourcePath}: folder name must be a lowercase URL slug.`);
  }

  requiredTextFields.forEach((field) => {
    if (typeof data[field] !== "string" || data[field].trim() === "") {
      fail(`${sourcePath}: "${field}" must be a non-empty string.`);
    }
  });

  if (!/^\d{4}-\d{2}-\d{2}$/.test(data.publishedAt)) {
    fail(`${sourcePath}: "publishedAt" must use YYYY-MM-DD format.`);
  }

  const parsedDate = new Date(`${data.publishedAt}T00:00:00Z`);
  if (Number.isNaN(parsedDate.valueOf()) || parsedDate.toISOString().slice(0, 10) !== data.publishedAt) {
    fail(`${sourcePath}: "publishedAt" must be a valid calendar date.`);
  }

  if (!Number.isInteger(data.readingTime) || data.readingTime < 1) {
    fail(`${sourcePath}: "readingTime" must be a positive whole number.`);
  }

  if (data.category !== undefined && (typeof data.category !== "string" || data.category.trim() === "")) {
    fail(`${sourcePath}: optional "category" must be a non-empty string.`);
  }

  if (data.featured !== undefined && typeof data.featured !== "boolean") {
    fail(`${sourcePath}: optional "featured" must be true or false.`);
  }
}

function readPosts() {
  if (!fs.existsSync(postsDirectory)) {
    fail(`Missing posts directory: ${postsDirectory}`);
  }

  const slugs = fs.readdirSync(postsDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  const seenSlugs = new Set();
  const posts = slugs.map((slug) => {
    const sourceFile = path.join(postsDirectory, slug, "index.md");
    const sourcePath = path.relative(projectRoot, sourceFile);

    if (!fs.existsSync(sourceFile)) {
      fail(`${sourcePath}: every post folder must contain index.md.`);
    }

    if (seenSlugs.has(slug)) {
      fail(`${sourcePath}: duplicate slug "${slug}".`);
    }
    seenSlugs.add(slug);

    const parsed = matter(fs.readFileSync(sourceFile, "utf8"));
    const data = {
      ...parsed.data,
      publishedAt: parsed.data.publishedAt instanceof Date
        ? parsed.data.publishedAt.toISOString().slice(0, 10)
        : parsed.data.publishedAt,
    };
    validatePost(slug, data, sourcePath);

    return {
      slug,
      title: data.title.trim(),
      summary: data.summary.trim(),
      publishedAt: data.publishedAt,
      readingTime: data.readingTime,
      category: data.category?.trim() || null,
      featured: data.featured ?? false,
      content: parsed.content.trim(),
    };
  });

  const featuredPosts = posts.filter((post) => post.featured);
  if (featuredPosts.length > 1) {
    fail(`Only one post can be featured; found ${featuredPosts.length}.`);
  }

  return posts.sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
}

const posts = readPosts();
const generatedSource = `// Generated by scripts/build-blog-content.js. Do not edit manually.\n\nexport const blogPosts = ${JSON.stringify(posts, null, 2)};\n`;

fs.mkdirSync(outputDirectory, { recursive: true });
fs.writeFileSync(outputFile, generatedSource);

console.log(`[blog:build] Generated ${posts.length} post${posts.length === 1 ? "" : "s"}.`);
